/**
 * Fast stemming & lookup helper for offline dict
 */
export function lookupOfflineDict(rawWord: string): DictEntry | null {
  if (!rawWord) return null;
  const word = rawWord.trim().toLowerCase().replace(/[^a-z]/g, '');
  if (!word || word.length < 2) return null;

  // Exact match
  if (offlineDict[word]) return offlineDict[word];

  // Common English suffix stemming rules
  const candidates = [
    word.replace(/s$/, ''),
    word.replace(/es$/, ''),
    word.replace(/ed$/, ''),
    word.replace(/ing$/, ''),
    word.replace(/ly$/, ''),
    word.replace(/tion$/, ''),
    word.replace(/ment$/, ''),
    word.replace(/ies$/, 'y'),
    word.replace(/ied$/, 'y'),
    word.replace(/ing$/, 'e'),
    word.replace(/ed$/, 'e'),
  ];

  for (const c of candidates) {
    if (c && offlineDict[c]) {
      return offlineDict[c];
    }
  }

  // Fallback entry for unmapped words so the user still gets pronunciation & word info
  return {
    word: rawWord,
    phonetic: `/${word}/`,
    pos: "word",
    translation: "暂未收录释义（支持点右侧喇叭体验朗读）"
  };
}
